use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const WASM_PACK_VERSION: &str = "wasm-pack 0.15.0";
const CRATE_RELATIVE: &str = "crates/kaspa-gateway-e2e-wasm";
const GENERATED_RELATIVE: &str = "e2e/generated/kgw_e2e_wasm";
const RUNTIME_PORTS_ADAPTER_RELATIVE: &str = "e2e/helpers/runtime-ports.mjs";
const ASSERTIONS_ADAPTER_RELATIVE: &str = "e2e/helpers/assertions.mjs";
const PATHS_ADAPTER_RELATIVE: &str = "e2e/helpers/paths.mjs";
const JS_NAME: &str = "kgw_e2e_wasm.js";
const WASM_NAME: &str = "kgw_e2e_wasm_bg.wasm";
const PACKAGE_NAME: &str = "package.json";

pub fn run_cli(args: &mut impl Iterator<Item = String>, root: &Path) -> Result<String, String> {
    let action = args.next().unwrap_or_else(|| "check".to_owned());
    if args.next().is_some() {
        return Err("e2e-wasm-codegen accepts exactly one action: check or write".to_owned());
    }
    match action.as_str() {
        "check" => check(root),
        "write" => write(root),
        _ => Err(format!(
            "unknown e2e-wasm-codegen action: {action}; expected check or write"
        )),
    }
}

